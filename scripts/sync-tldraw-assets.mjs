#!/usr/bin/env zx
/*
  sync-tldraw-assets.mjs
  - Requires: zx (https://github.com/google/zx)
  - Usage: zx ./scripts/sync-tldraw-assets.mjs
  This script scans node_modules/@tldraw/assets for fonts, icons, translations and embed-icons
  and generates src/tw-whiteboard/tldraw/assets/tiddlywiki.files which contains tiddlers
  pointing to those files so TiddlyWiki can package them into the plugin for offline use.
*/

import fs from 'fs';
import path from 'path';

const root = path.resolve(process.cwd());
const assetsPkg = path.join(root, 'node_modules', '@tldraw', 'assets');
const targetDir = path.join(root, 'src', 'tw-whiteboard', 'tldraw', 'assets');
const targetFile = path.join(targetDir, 'tiddlywiki.files');
const targetAssetUrlFile = path.join(targetDir, 'getAssetUrlsByMetaUrl.ts');
const upstreamAssetUrlsFile = path.join(assetsPkg, 'urls.js');

function exists(p) {
  try { return fs.existsSync(p); } catch (e) { return false; }
}

function relToAssets(p) {
  // relative from our tiddlywiki.files location to node_modules/@tldraw/assets
  const from = path.join('..', '..', '..', '..', 'node_modules', '@tldraw', 'assets');
  return path.posix.join(from.split(path.sep).join('/'), p.split(path.sep).join('/'));
}

function tiddlerEntry(filePath, title, type) {
  return {
    file: filePath,
    fields: {
      type: type,
      title: title
    }
  };
}

function getMimeTypeForExtension(ext) {
  switch (ext) {
    case '.woff2':
      return 'font/woff2';
    case '.woff':
      return 'font/woff';
    case '.ttf':
      return 'font/ttf';
    case '.otf':
      return 'font/otf';
    case '.svg':
      return 'image/svg+xml';
    case '.png':
      return 'image/png';
    case '.jpg':
    case '.jpeg':
      return 'image/jpeg';
    case '.json':
      return 'application/json';
    default:
      return 'application/octet-stream';
  }
}

function generateAssetUrlSource() {
  if (!exists(upstreamAssetUrlsFile)) {
    throw new Error(`Cannot find upstream asset urls file at ${upstreamAssetUrlsFile}`);
  }

  const upstreamSource = fs.readFileSync(upstreamAssetUrlsFile, 'utf8');
  const functionStartToken = 'export function getAssetUrlsByMetaUrl(opts) {';
  const functionStart = upstreamSource.indexOf(functionStartToken);

  if (functionStart < 0) {
    throw new Error(`Cannot find ${functionStartToken} in ${upstreamAssetUrlsFile}`);
  }

  let transformed = upstreamSource.slice(functionStart);

  transformed = transformed.replace(
    /export function getAssetUrlsByMetaUrl\(opts\) \{\s*const iconsIcon0MergedSvg = formatAssetUrl\(\s*new URL\('\.\/icons\/icon\/0_merged\.svg', import\.meta\.url\)\.href,\s*opts\s*\)/,
    [
      'export function getAssetUrlsByMetaUrl(fn: (item: string) => string) {',
      "\tconst iconsIcon0MergedSvg = fn('icons/icon/0_merged.svg')",
    ].join('\n'),
  );

  transformed = transformed.replace(
    /formatAssetUrl\(\s*new URL\('\.\/([^']+)', import\.meta\.url\)\.href,\s*opts\s*\)/g,
    (_match, assetPath) => `fn('${assetPath}')`,
  );

  transformed = transformed.replace(/iconsIcon0MergedSvg \+ '#([^']+)'/g, (_match, iconName) => `fn('icons/icon/${iconName}.svg')`);
  transformed = transformed.replace("\tconst iconsIcon0MergedSvg = fn('icons/icon/0_merged.svg')\n", '');

  transformed = transformed.replace('icons: {', "icons: {\n\t\t\t...getCustomIcons(fn),");
  transformed = transformed.replace(/\n\t*$/u, '\n');

  return [
    '/* eslint-disable unicorn/prevent-abbreviations */',
    '// Copied from @tldraw/assets/urls.js',
    '// Generated by scripts/sync-tldraw-assets.mjs. Do not edit manually.',
    '',
    "import { getCustomIcons } from './customAssets';",
    '',
    transformed,
  ].join('\n');
}

function scanDir(dir, extFilter) {
  const out = [];
  if (!exists(dir)) return out;
  const files = fs.readdirSync(dir, { withFileTypes: true });
  for (const f of files) {
    if (f.isFile()) {
      if (!extFilter || extFilter.includes(path.extname(f.name).toLowerCase())) {
        out.push(path.join(dir, f.name));
      }
    } else if (f.isDirectory()) {
      const sub = scanDir(path.join(dir, f.name), extFilter);
      for (const s of sub) out.push(s);
    }
  }
  return out;
}

// ensure target dir exists
fs.mkdirSync(targetDir, { recursive: true });

// overwrite existing file (no backup by request)

const result = { tiddlers: [] };

// fonts
const fontsDir = path.join(assetsPkg, 'fonts');
const fonts = scanDir(fontsDir, ['.woff', '.woff2', '.ttf', '.otf']);
for (const f of fonts) {
  const rel = relToAssets(path.relative(assetsPkg, f));
  const title = `$:/plugins/linonetwo/tw-whiteboard/assets/${path.relative(assetsPkg, f).split(path.sep).join('/')}`;
  result.tiddlers.push(tiddlerEntry(rel, title, getMimeTypeForExtension(path.extname(f).toLowerCase())));
}

// icons (icons/icon)
const iconsDir = path.join(assetsPkg, 'icons');
const icons = scanDir(iconsDir, ['.svg', '.png', '.jpg']);
for (const f of icons) {
  const rel = relToAssets(path.relative(assetsPkg, f));
  const title = `$:/plugins/linonetwo/tw-whiteboard/assets/${path.relative(assetsPkg, f).split(path.sep).join('/')}`;
  result.tiddlers.push(tiddlerEntry(rel, title, getMimeTypeForExtension(path.extname(f).toLowerCase())));
}

// embed-icons
const embedDir = path.join(assetsPkg, 'embed-icons');
const embeds = scanDir(embedDir, ['.png', '.jpg']);
for (const f of embeds) {
  const rel = relToAssets(path.relative(assetsPkg, f));
  const title = `$:/plugins/linonetwo/tw-whiteboard/assets/${path.relative(assetsPkg, f).split(path.sep).join('/')}`;
  result.tiddlers.push(tiddlerEntry(rel, title, getMimeTypeForExtension(path.extname(f).toLowerCase())));
}

// translations
const translationsDir = path.join(assetsPkg, 'translations');
const translations = scanDir(translationsDir, ['.json']);
for (const f of translations) {
  const rel = relToAssets(path.relative(assetsPkg, f));
  const title = `$:/plugins/linonetwo/tw-whiteboard/assets/${path.relative(assetsPkg, f).split(path.sep).join('/')}`;
  result.tiddlers.push(tiddlerEntry(rel, title, getMimeTypeForExtension(path.extname(f).toLowerCase())));
}

// Deduplicate by file path
const seen = new Set();
result.tiddlers = result.tiddlers.filter(t => {
  if (seen.has(t.file)) return false;
  seen.add(t.file);
  return true;
});

// sort entries for reproducibility
result.tiddlers.sort((a, b) => a.file.localeCompare(b.file));

// write tiddlywiki.files
fs.writeFileSync(targetFile, JSON.stringify(result, null, 2) + '\n', 'utf8');
fs.writeFileSync(targetAssetUrlFile, generateAssetUrlSource(), 'utf8');
console.log(`Wrote ${targetFile} with ${result.tiddlers.length} entries.`);
console.log(`Wrote ${targetAssetUrlFile}.`);

console.log('Done. Please run your dev server and verify no network requests go to unpkg for @tldraw/assets.');
